static inline uint32_t
adreno8_pm4_type7(uint32_t opcode, uint32_t count)
{
	uint32_t a = opcode, b = count, pa = 1, pb = 1;
	while (a) { pa ^= a & 1; a >>= 1; }
	while (b) { pb ^= b & 1; b >>= 1; }
	return 0x70000000u | count | (pb << 15) | (opcode << 16) | (pa << 23);
}

static inline uint32_t
adreno8_pm4_cp_init(uint32_t *words, uint32_t capacity, uint64_t address)
{
	if (!words || capacity < 10 || !address || (address & 3) || address >= (1ULL << 32))
		return 0;
	words[0] = adreno8_pm4_type7(0x17, 1);
	words[1] = 1u << 27;
	words[2] = adreno8_pm4_type7(0x48, 7);
	words[3] = 0x14b;
	words[4] = 3;
	words[5] = 0x20000000;
	words[6] = 2;
	words[7] = (uint32_t)address;
	words[8] = 0;
	words[9] = 1u << 31;
	return 10;
}

static inline uint32_t
adreno8_pm4_secure_exit(uint32_t *words, uint32_t capacity)
{
	if (!words || capacity < 2)
		return 0;
	words[0] = adreno8_pm4_type7(0x66, 1);
	words[1] = 0;
	return 2;
}

static inline uint32_t
adreno8_pm4_scratch(uint32_t *words, uint32_t capacity, uint64_t address, uint32_t value)
{
	if (!words || capacity < 6 || !address || (address & 3) || address >= (1ULL << 32))
		return 0;
	words[0] = adreno8_pm4_type7(0x3d, 3);
	words[1] = (uint32_t)address;
	words[2] = 0;
	words[3] = value;
	words[4] = adreno8_pm4_type7(0x12, 0); /* CP_WAIT_MEM_WRITES */
	words[5] = adreno8_pm4_type7(0x26, 0); /* CP_WAIT_FOR_IDLE */
	return 6;
}

